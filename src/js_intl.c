int ji_install(js_context *ctx) {
    if (ctx == NULL) return -1;
    JSContext *c = (JSContext *)js_context_raw(ctx);
    if (c == NULL) return -1;

    /* Host code: compiled without source, like every shim (spec/js_native.md). */
    JSRuntime *rt = JS_GetRuntime(c);
    bool hid = JS_SetHideSource(rt, true);
    JSValue fn = JS_Eval(c, JI_SHIM, sizeof JI_SHIM - 1, "<intl>", JS_EVAL_TYPE_GLOBAL);
    (void)JS_SetHideSource(rt, hid);
    if (JS_IsException(fn)) { JS_FreeValue(c, JS_GetException(c)); return -1; }

    JSValue global = JS_GetGlobalObject(c);
    JSValue r = JS_Call(c, fn, JS_UNDEFINED, 1, &global);
    int rc = 0;
    if (JS_IsException(r)) { JS_FreeValue(c, JS_GetException(c)); rc = -1; }
    JS_FreeValue(c, r);
    JS_FreeValue(c, global);
    JS_FreeValue(c, fn);
    return rc;
}
