/*
 * js_custom_elements -- Custom Elements v1 over the document facade (spec/js_custom_elements.md).
 * The runtime is embedded JavaScript: the DOM wrappers are JS objects, so the registry, the
 * HTMLElement constructor and the lifecycle reconciliation live next to them. Nothing here
 * touches the network or the host; the only new capability is running the page's own class
 * constructors, which the page's JS could already do.
 */

#include "js_custom_elements.h"

static const char JDCE_SHIM[] =
    "(function(){\n"
    "  var g=__G, doc=g.document;\n"
    "  if(!doc||typeof g.HTMLElement!=='function') return;\n"
    "  var RESERVED={'annotation-xml':1,'color-profile':1,'font-face':1,'font-face-src':1,'font-face-uri':1,\n"
    "    'font-face-format':1,'font-face-name':1,'missing-glyph':1};\n"
    "  var LIVE_MAX=4096;\n"
    "  var defs=Object.create(null), byCtor=new Map(), waiters=Object.create(null);\n"
    "  var live=[], done=new WeakSet(), upgrading=null, flushing=false;\n"
    "  var rawCreate=doc.createElement.bind(doc);\n"
    "  var P=g.HTMLElement.prototype;\n"
    "  function ex(msg,name){ try{ return new g.DOMException(msg,name); }catch(e){ var x=new Error(msg); x.name=name; return x; } }\n"
    "  function report(e){ try{ if(g.console&&g.console.error) g.console.error(e); }catch(x){} }\n"
    "  /* The real constructor: only a defined class may call it. It hands back the element being\n"
    "   * upgraded, or a fresh one, with the class prototype in front of the wrapper. */\n"
    "  function HTMLElement(){\n"
    "    var nt=new.target;\n"
    "    if(nt===undefined||nt===HTMLElement) throw new TypeError('Illegal constructor');\n"
    "    var def=byCtor.get(nt);\n"
    "    if(!def) throw new TypeError('Illegal constructor');\n"
    "    var el=(upgrading!==null)?upgrading:rawCreate(def.name);\n"
    "    upgrading=null;\n"
    "    if(Object.getPrototypeOf(el)!==nt.prototype) Object.setPrototypeOf(el,nt.prototype);\n"
    "    return el;\n"
    "  }\n"
    "  HTMLElement.prototype=P;\n"
    "  Object.defineProperty(P,'constructor',{value:HTMLElement,writable:true,configurable:true});\n"
    "  try{ Object.setPrototypeOf(HTMLElement,g.Element); }catch(e){}\n"
    "  g.HTMLElement=HTMLElement;\n"
    "  function isConn(el){\n"
    "    var de=doc.documentElement, n=el;\n"
    "    for(var i=0;n&&i<4096;i++){ if(n===de) return true; n=n.parentNode; }\n"
    "    return false;\n"
    "  }\n"
    "  function track(el,def){\n"
    "    if(done.has(el)) return null;\n"
    "    done.add(el);\n"
    "    var rec={el:el,def:def,connected:false,attrs:Object.create(null)};\n"
    "    for(var i=0;i<def.observed.length;i++) rec.attrs[def.observed[i]]=el.getAttribute(def.observed[i]);\n"
    "    live.push(rec);\n"
    "    if(live.length>LIVE_MAX){\n"
    "      for(var k=0;k<live.length&&live.length>LIVE_MAX;k++) if(!live[k].connected){ live.splice(k,1); k--; }\n"
    "    }\n"
    "    return rec;\n"
    "  }\n"
    "  function call(el,name,args){\n"
    "    var f=el[name];\n"
    "    if(typeof f==='function'){ try{ f.apply(el,args); }catch(e){ report(e); } }\n"
    "  }\n"
    "  function construct(def){\n"
    "    var el;\n"
    "    try{ el=new def.ctor(); }catch(e){ report(e); el=rawCreate(def.name); return el; }\n"
    "    track(el,def);\n"
    "    return el;\n"
    "  }\n"
    "  function upgrade(el,def){\n"
    "    if(done.has(el)) return;\n"
    "    done.add(el);\n"
    "    var saved=upgrading; upgrading=el;\n"
    "    try{ new def.ctor(); }catch(e){ report(e); }\n"
    "    upgrading=saved;\n"
    "    var rec={el:el,def:def,connected:false,attrs:Object.create(null)};\n"
    "    live.push(rec);\n"
    "    for(var i=0;i<def.observed.length;i++){\n"
    "      var n=def.observed[i], v=el.getAttribute(n);\n"
    "      rec.attrs[n]=v;\n"
    "      if(v!==null) call(el,'attributeChangedCallback',[n,null,v]);\n"
    "    }\n"
    "  }\n"
    "  function scan(root,only){\n"
    "    var names=only?[only]:Object.keys(defs);\n"
    "    if(names.length===0||!root||typeof root.querySelectorAll!=='function') return;\n"
    "    var list=root.querySelectorAll(names.join(','));\n"
    "    for(var i=0;i<list.length;i++){\n"
    "      var el=list[i];\n"
    "      if(done.has(el)) continue;\n"
    "      var d=defs[(el.localName||el.tagName||'').toLowerCase()];\n"
    "      if(d) upgrade(el,d);\n"
    "    }\n"
    "  }\n"
    "  /* `only` = a just-defined name: define() must not rescan the whole document for EVERY\n"
    "   * known name nor reconcile every live element (that is O(defines^2 x DOM): GitHub defines\n"
    "   * hundreds), only upgrade and connect the elements of that one name. */\n"
    "  function flush(root,only){\n"
    "    if(flushing) return;\n"
    "    flushing=true;\n"
    "    try{\n"
    "      scan(root||doc,only);\n"
    "      var snap=live.slice();\n"
    "      for(var i=0;i<snap.length;i++){\n"
    "        var r=snap[i], el=r.el;\n"
    "        if(only&&r.def.name!==only) continue;\n"
    "        for(var k=0;k<r.def.observed.length;k++){\n"
    "          var n=r.def.observed[k], nv=el.getAttribute(n);\n"
    "          if(nv!==r.attrs[n]){ var ov=r.attrs[n]; r.attrs[n]=nv; call(el,'attributeChangedCallback',[n,ov,nv]); }\n"
    "        }\n"
    "        var conn=isConn(el);\n"
    "        if(conn&&!r.connected){ r.connected=true; call(el,'connectedCallback',[]); }\n"
    "        else if(!conn&&r.connected){ r.connected=false; call(el,'disconnectedCallback',[]); }\n"
    "      }\n"
    "    }finally{ flushing=false; }\n"
    "  }\n"
    "  doc.createElement=function(t){\n"
    "    var def=defs[String(t).toLowerCase()];\n"
    "    return def?construct(def):rawCreate(t);\n"
    "  };\n"
    "  var ce={\n"
    "    define:function(name,ctor){\n"
    "      name=String(name);\n"
    "      if(typeof ctor!=='function') throw new TypeError('The constructor must be a function');\n"
    "      if(!/^[a-z][a-z0-9._]*-[a-z0-9._-]*$/.test(name)||RESERVED[name]) throw ex(\"'\"+name+\"' is not a valid custom element name\",'SyntaxError');\n"
    "      if(defs[name]) throw ex(\"'\"+name+\"' has already been defined\",'NotSupportedError');\n"
    "      if(byCtor.has(ctor)) throw ex('This constructor has already been used with this registry','NotSupportedError');\n"
    "      var obs=[];\n"
    "      try{ var oa=ctor.observedAttributes; if(oa&&typeof oa[Symbol.iterator]==='function') obs=Array.from(oa,String); }catch(e){ report(e); }\n"
    "      var def={name:name,ctor:ctor,observed:obs};\n"
    "      defs[name]=def; byCtor.set(ctor,def);\n"
    "      var w=waiters[name]; if(w){ delete waiters[name]; for(var i=0;i<w.length;i++) w[i](ctor); }\n"
    "      flush(undefined,name);\n"
    "    },\n"
    "    get:function(name){ var d=defs[String(name)]; return d?d.ctor:undefined; },\n"
    "    getName:function(ctor){ var d=byCtor.get(ctor); return d?d.name:null; },\n"
    "    whenDefined:function(name){\n"
    "      name=String(name);\n"
    "      if(!/^[a-z][a-z0-9._]*-[a-z0-9._-]*$/.test(name)) return Promise.reject(ex(\"'\"+name+\"' is not a valid custom element name\",'SyntaxError'));\n"
    "      if(defs[name]) return Promise.resolve(defs[name].ctor);\n"
    "      return new Promise(function(res){ (waiters[name]||(waiters[name]=[])).push(res); });\n"
    "    },\n"
    "    upgrade:function(root){ flush(root||doc); }\n"
    "  };\n"
    "  var sel='';\n"
    "  var rdef=ce.define;\n"
    "  ce.define=function(name,ctor){ rdef.call(ce,name,ctor); sel=Object.keys(defs).join(','); };\n"
    "  /* Synchronous reconciliation after a DOM mutation, scoped to the nodes it touched and only\n"
    "   * when one of them is, or contains, a custom element -- every other mutation costs nothing. */\n"
    "  g.__ceTouch=function(nodes){\n"
    "    if(flushing||sel===''||!nodes) return;\n"
    "    var hit=[];\n"
    "    for(var i=0;i<nodes.length;i++){\n"
    "      var n=nodes[i];\n"
    "      if(!n||n.nodeType!==1) continue;\n"
    "      var tag=(n.localName||n.tagName||'').toLowerCase();\n"
    "      if(done.has(n)||defs[tag]||(typeof n.querySelector==='function'&&n.querySelector(sel))) hit.push(n);\n"
    "    }\n"
    "    if(hit.length===0) return;\n"
    "    flushing=true;\n"
    "    try{\n"
    "      for(var a=0;a<hit.length;a++){\n"
    "        var t=(hit[a].localName||hit[a].tagName||'').toLowerCase();\n"
    "        if(defs[t]&&!done.has(hit[a])) upgrade(hit[a],defs[t]);\n"
    "        scan(hit[a]);\n"
    "      }\n"
    "      var snap=live.slice();\n"
    "      for(var j=0;j<snap.length;j++){\n"
    "        var r=snap[j], el=r.el, rel=false;\n"
    "        for(var b=0;b<hit.length&&!rel;b++) rel=(hit[b]===el)||(typeof hit[b].contains==='function'&&hit[b].contains(el));\n"
    "        if(!rel) continue;\n"
    "        var conn=isConn(el);\n"
    "        if(conn&&!r.connected){ r.connected=true; call(el,'connectedCallback',[]); }\n"
    "        else if(!conn&&r.connected){ r.connected=false; call(el,'disconnectedCallback',[]); }\n"
    "      }\n"
    "    }finally{ flushing=false; }\n"
    "  };\n"
    "  g.customElements=ce;\n"
    "  g.__ceFlush=function(){ flush(); };\n"
    "  g.__connectedCallback=function(){ flush(); };\n"
    "  ['__tickTimers','__fireDeferred'].forEach(function(n){\n"
    "    var f=g[n];\n"
    "    if(typeof f==='function') g[n]=function(){ var r=f.apply(this,arguments); flush(); return r; };\n"
    "  });\n"
    "})();\n";

int jdce_install(JSContext *ctx) {
    JSValue r = JS_Eval(ctx, JDCE_SHIM, sizeof JDCE_SHIM - 1, "<custom-elements>", JS_EVAL_TYPE_GLOBAL);
    int ok = !JS_IsException(r);
    JS_FreeValue(ctx, r);
    return ok ? 0 : -1;
}
